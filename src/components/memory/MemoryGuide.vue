<template>
  <Sheet :open="open" title="记忆库说明书" @close="$emit('close')">
    <div class="guide">
      <p>右上角 ⚙ 是记忆设置：聊天带多少原文、卡片张数、共读字数、共写带多少讨论、整理模型都在那里。</p>
      <p>发给{{ him }}的记忆分两种。每一种都能在这里看到、改错；每一处都有「看看发给{{ him }}的」，能看到原样发过去的全部内容。</p>

      <h4>① 全局记忆：在哪都带着</h4>
      <ul>
        <li><b>记忆卡片</b>分五类，每张卡片其实记着两件事：现在还成不成立、平时怎么给他。
          <ul>
            <li><b>常驻</b>：每次、每个房间都带着，最多 20 张；满了会提醒你，不会自己挤掉旧的。</li>
            <li><b>普通</b>：确认过的默认放这里。平时不全带，按你最新说的话自动想起最相关的几张（⚙ 里调几张，对不上就一张也不放）；他想不起来也可以「翻记忆」。</li>
            <li><b>归档</b>：还成立但不常用了。不自动想起，只在搜索时出现（搜索时可以勾掉「包含归档」）。</li>
            <li><b>待确认</b>：整理摘要、前情、讨论摘要时，整理模型顺手挑出来的。确认前不给他、不自动想起；确认后进普通，也可以直接设为常驻。</li>
            <li><b>已过时</b>：以前成立、现在不是了（比如病好了）。留作历史，不当成现在的事；搜索时勾上「包含已过时」才找得到，他翻记忆时会看到标着「已过时」。</li>
          </ul>
          删除会先进回收站，不再给他；回收站里可以恢复，也可以彻底删掉。每张卡都记着来源（聊天 / 共读 / 共写 / 你手动 / 整理时挑的）、谁写的、创建和更新时间、标签和重要程度。{{ him }}自己也能改：写卡、改卡、标已过时、归档、设为常驻。</li>
        <li><b>来往的信</b>：他读过的你的信、他写的信，留标题和开头一句（最近 10 封），他以后提得起来。</li>
        <li><b>聊天摘要</b>：聊久了，前面的聊天会整理成一份摘要。一直只有一份：每次整理都是把旧摘要和新聊的合在一起，整理成新的。什么时候整理：摘要后面的聊天原文到了「每次带多少聊天原文」（默认 5 万 token，按字数估）的八成，或者内容到了模型上限的七成，或者你点「现在整理」；最近一半留着原样。每次整理、改动之前的那份都留一个历史版本（整理了哪段、什么时候、用的哪个模型），整理坏了能退回。在小世界里可以随时看、改。换到新对话时，摘要会跟着过去。</li>
        <li><b>从共读、共写整理来的</b>：读书笔记、写书的总结。在全局记忆里它们排在记忆卡片后面，分开标好。</li>
      </ul>
      <p class="sub">平时聊天的顺序：说话方式 → 各种规矩 → 全局记忆（记忆卡片 → 读书笔记 → 写书总结）→ 摘要记忆 → 最近的聊天 → 【此刻】（时间、心境、最近 24 小时的事、想起的普通卡片）→ 你的新消息。</p>

      <h4>灵感抽屉</h4>
      <p class="sub">共写书桌上面的「灵感抽屉」：不属于哪本在写的书。杂乱的灵感卡片，和以前的书（一本一组，只有卡片，写复盘）；卡片和书都能加标签、按标签筛。打开也是和他聊，东西在右上角的抽屉里；讨论像共写一样到 3 万 token 的八成就整理。大概的样子（几张灵感、有哪些以前的书、常用的标签）放在全局记忆的板块记忆里；翻记忆也能翻到抽屉里的卡片。</p>
      <h4>他定期整理记忆卡片</h4>
      <p class="sub">每隔两周（⚙ 里调，也可以关掉），他会用自己的模型把记忆卡片从头看一遍，提出整理建议：合并说同一件事的、改写过时的内容、标已过时、归档、设为常驻或取消常驻、确认或丢掉待确认的、补一张缺的，最后写几句给你的话。都只是建议：记忆库上面「整理建议」里一条条采纳或跳过，也能全部照做；采纳了还能撤回（合并时原来的卡片进回收站，撤回就放回来）。你也可以随时点「现在让他整理一遍」。</p>
      <h4>记忆体检</h4>
      <p class="sub">记忆库上面「记忆体检」：卡片各有多少；哪两张说的可能是同一件事；各个房间的摘要什么时候整理的、被重新压了几次（压得太多可以翻历史版本对一对）；哪些房间快到整理的时候；每次聊天大概带多少 token、都花在哪；最近按你的话自动想起了哪些卡片、他翻过什么；哪些卡片一个多月没用上。最上面会挑出要留意的事。</p>
      <h4>翻记忆（他自己找）</h4>
      <p class="sub">他想不起以前的事，会写 [翻记忆:关键词]，也可以加范围和时间：[翻记忆:关键词|共读|上个月]。会在所有对话（含邮箱那边）、共写讨论、书里的划线批注和他的中途印象、来往的信、记忆卡片、各处的摘要里找。两路一起找：所有词都原样出现的，和拆成小块以后最像的（BM25，说法不完全一样也能找到）；再按两边各排第几合起来（RRF），常驻、重要、最近一个月的稍靠前，已过时的靠后。聊天里找到的那句，会带上前后各一句。几千条也就几十毫秒，不会变慢。记忆库上面「试试翻记忆」能看到他会翻到什么。</p>
      <h4>板块记忆（长期的进展）</h4>
      <p class="sub">放在全局记忆里一直带着，不像此刻那样 24 小时就忘：在写的书各自「现在到哪了 / 下一步」（他讨论时、整理讨论时会自己更新，你在共写「⋯」里也能改；归档了就不再记）；在读的书读到哪，读完的书一句印象（100 字以内，读完时整理模型写，重读的标「第几次」）；邮箱里的笔友每人一句话（50 字以内）。记忆库「全局记忆」里都能看、能改。</p>
      <h4>② 此刻（最近 24 小时）</h4>
      <p class="sub">附在你新消息前面的，只管最近 24 小时，时间都写成「3 小时前」这样（每次现算）：24 小时里寄出、读过的信（最多 3 封，标题和第一句；你新寄的他读一次全文；他寄的你没拆就一直挂着）；24 小时里读过的每本书（读到哪、他最新的印象、最多 20 条来往的划线批注）；还有他自己用 [此刻:…] 记的小事（最多 3 条，35 字以内，24 小时后自动忘）。共读、共写里也带着一份简短的。记忆库「全局记忆」里能看到现在带着什么。</p>

      <h4>③ 场景记忆：只在那个地方才带</h4>
      <ul>
        <li><b>共读</b>：前情梗概（整理模型客观写的，一段段接着；攒到 6 万字、等一章读完整理一段，只整理新读的）→ 他最新的中途印象（每 2 万字他自己写一句，每一版都留着）→ 最近的划线和批注 → 这本书的读书笔记 → 其他也在读的书（一句话，免得弄混）→ 全局记忆 → 上次整理之后读过的原文（全部看得见）→ 这次的原文。读完可以请他写读后感（最多 3000 字），重写不覆盖，每篇标着第几遍。</li>
        <li><b>共写</b>：定位、简介、资料（按你排的顺序）→ 他记着的这本书（你手动记的）→ 讨论摘要 → 摘要之后的讨论原文（默认 3 万 token，到八成整理，也留历史版本）→ 其他在写的书（一句话）→ 全局记忆。讨论摘要只在这本书里，不进记忆库。</li>
      </ul>
      <p class="sub">进到共读、共写里，场景记忆排在全局记忆前面。这里的全局记忆是：记忆卡片、聊天摘要、主聊天里最近的消息（默认约 6 千 token，记忆设置里调），他在哪都还是同一个他；和这个场景重复的部分不放。</p>

      <h4>④ 信箱</h4>
      <p class="sub">你写的信，{{ him }}下一次聊天时读一遍全文；之后全局记忆里只留标题和开头一句。</p>

      <h4>⑤ 用的模型</h4>
      <p class="sub">整理类的活（聊天摘要、共读的前情、共写的讨论摘要和总结）用「设置 → API」里的「整理用的模型」，可以选便宜的。{{ him }}说的话、划线批注、记忆卡片，还是用{{ him }}自己的模型。</p>
    </div>
  </Sheet>
